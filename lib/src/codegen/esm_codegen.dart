final class CodegenReturn {
  const CodegenReturn({required this.code});

  final String code;
}

final class Codegen {
  const Codegen();

  CodegenReturn generate(EsmModule module, {bool minify = false}) {
    final printer = _EsmPrinter(compact: minify);
    return CodegenReturn(code: printer.print(module));
  }
}

final class _EsmPrinter {
  _EsmPrinter({this.compact = false});

  final bool compact;
  final _buffer = StringBuffer();
  var _indent = 0;

  String print(EsmModule module) {
    if (!compact) {
      _buffer.writeln('// Generated by dart2esm.');
      _buffer.writeln();
    }
    for (var i = 0; i < module.items.length; i++) {
      _emitModuleItem(module.items[i]);
      if (compact) _buffer.writeln();
      if (!compact &&
          i != module.items.length - 1 &&
          _needsBlankLineBetween(module.items[i], module.items[i + 1])) {
        _buffer.writeln();
      }
    }
    return _buffer.toString();
  }

  void _writeIndented(String line) {
    if (compact) {
      _buffer.write(line.trim());
      return;
    }
    _buffer.write('  ' * _indent);
    _buffer.writeln(line);
  }
}
